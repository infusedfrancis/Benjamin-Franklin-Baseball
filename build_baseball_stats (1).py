def clean_name(s):
    return re.sub(r'\s*\((?:Fr|So|Jr|Sr)\)', '', str(s)).strip()

def get_class(s):
    m = re.search(r'\((Fr|So|Jr|Sr)\)', str(s))
    return m.group(1) if m else ''

def grad_year(season_str, cls):
    end = int('20' + season_str.split('-')[1])
    off = {'Fr': 3, 'So': 2, 'Jr': 1, 'Sr': 0}
    return end + off[cls] if cls in off else None

def player_key(raw_name, season):
    cls = get_class(raw_name)
    cn  = clean_name(raw_name)
    gy  = grad_year(season, cls)
    return f"{cn} '{str(gy)[-2:]}" if gy else cn

def ip_dec(ip):
    """7.2  →  7.6̄  (7 + 2/3 innings as decimal)"""
    if ip is None or ip == '': return 0.0
    try:
        v = float(ip); w = int(v); f = round((v - w)*10)
        return w + f/3.0
    except: return 0.0

def ip_thirds(ip):
    if ip is None or ip == '': return 0
    try:
        v = float(ip); w = int(v); f = round((v - w)*10)
        return w*3 + f
    except: return 0

def thirds_str(t):
    if t == 0: return '0'
    w = t//3; f = t%3
    return str(w) if f == 0 else f'{w}.{f}'

def n(v): return v if v is not None else 0

