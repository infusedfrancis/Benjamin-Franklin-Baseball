def style_header(ws, row_num, fill_hex=NAVY, font_hex=GOLD):
    fill = PatternFill("solid", fgColor=fill_hex)
    font = Font(bold=True, color=font_hex, size=11)
    for cell in ws[row_num]:
        cell.fill = fill
        cell.font = font
        cell.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)

def style_rows(ws, start_row, end_row, num_cols):
    lgray = PatternFill("solid", fgColor=LGRAY)
    white = PatternFill("solid", fgColor=WHITE)
    thin  = Side(style='thin', color='CCCCCC')
    border= Border(bottom=thin)
    for r in range(start_row, end_row+1):
        fill = lgray if r % 2 == 0 else white
        for c in range(1, num_cols+1):
            cell = ws.cell(row=r, column=c)
            cell.fill = fill
            cell.border = border
            cell.alignment = Alignment(horizontal='center', vertical='center')

def write_df(ws, df, include_index=False):
    """Write a DataFrame to worksheet starting at row 1."""
    for r_idx, row in enumerate(dataframe_to_rows(df, index=include_index, header=True), 1):
        for c_idx, val in enumerate(row, 1):
            ws.cell(row=r_idx, column=c_idx, value=val)
    style_header(ws, 1)
    style_rows(ws, 2, len(df)+1, ws.max_column)
    ws.freeze_panes = 'A2'

def auto_fit(ws, min_w=8, max_w=32):
    for col in ws.columns:
        max_len = 0
        col_letter = get_column_letter(col[0].column)
        for cell in col:
            try:
                l = len(str(cell.value)) if cell.value is not None else 0
                max_len = max(max_len, l)
            except: pass
        ws.column_dimensions[col_letter].width = max(min_w, min(max_w, max_len + 2))

# Columns that are rate stats → 3-decimal baseball format (no leading zero for <1)
_RATE_COLS = {'AVG','OBP','SLG','OPS','ERA','WHIP','K/9','BB/9','W%',
              'W_pct','FP','CS%'}
_RATE_FMT  = '#.000'   # shows .435 not 0.435; shows 4.350 not 4.35

def apply_formats_and_filter(ws, title_rows=2):
    """Apply #.000 format to rate-stat columns and enable AutoFilter on all columns."""
    header_row = title_rows + 1          # row 3 after two title rows

    # Map column name → column index from the header row
    col_map = {}
    for cell in ws[header_row]:
        if cell.value is not None:
            col_map[str(cell.value)] = cell.column

    # Apply rate format to matching columns
    for col_name, col_idx in col_map.items():
        if col_name in _RATE_COLS:
            for row in ws.iter_rows(min_row=header_row + 1,
                                     max_row=ws.max_row,
                                     min_col=col_idx, max_col=col_idx):
                for cell in row:
                    if cell.value is not None:
                        cell.number_format = _RATE_FMT

    # AutoFilter spanning the full header + data range
    last_col = get_column_letter(ws.max_column)
    last_row = ws.max_row
    ws.auto_filter.ref = f"A{header_row}:{last_col}{last_row}"

    # Freeze below header (so title + header stay fixed while scrolling)
    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)

