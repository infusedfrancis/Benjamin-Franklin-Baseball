def career_batting(df):
    cnt_cols = ['GP','PA','AB','R','H','RBI','2B','3B','HR','SF','SH','BB','K','HBP','SB']
    grp = df.groupby('PlayerKey', sort=False)

    rows = []
    for pk, g in grp:
        seasons_played = ', '.join(sorted(g['Season'].tolist()))
        num_seasons    = g['Season'].nunique()
        player         = g['Player'].iloc[0]
        gy             = g['GradYr'].iloc[0]
        cls_list       = g['Class'].tolist()

        sums = {}
        for c in cnt_cols:
            sums[c] = int(g[c].fillna(0).sum())

        ab  = sums['AB'];  h  = sums['H']
        bb  = sums['BB'];  hbp= sums['HBP']; sf = sums['SF']
        b2  = sums['2B'];  b3 = sums['3B'];  hr = sums['HR']

        avg = round(h/ab, 3) if ab > 0 else 0.0
        obp_d = (h+bb+hbp)/(ab+bb+hbp+sf) if (ab+bb+hbp+sf) > 0 else 0.0
        tb  = h + b2 + 2*b3 + 3*hr
        slg_d = tb/ab if ab > 0 else 0.0
        ops_d = obp_d + slg_d

        rows.append([player, gy, pk, num_seasons, seasons_played,
                     sums['GP'], avg, sums['PA'], ab,
                     sums['R'], h, sums['RBI'], sums['2B'], sums['3B'], sums['HR'],
                     sums['SF'], sums['SH'], sums['BB'], sums['K'], sums['HBP'],
                     sums['SB'],
                     round(obp_d,3), round(slg_d,3), round(ops_d,3)])

    cols = ['Player','GradYr','PlayerKey','Seasons','SeasonList',
            'GP','AVG','PA','AB','R','H','RBI','2B','3B','HR',
            'SF','SH','BB','K','HBP','SB','OBP','SLG','OPS']
    df_out = pd.DataFrame(rows, columns=cols)
    df_out = df_out.sort_values('H', ascending=False).reset_index(drop=True)
    return df_out

