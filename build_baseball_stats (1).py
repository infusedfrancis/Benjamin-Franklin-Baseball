def career_pitching(df):
    grp = df.groupby('PlayerKey', sort=False)
    rows = []
    for pk, g in grp:
        seasons_played = ', '.join(sorted(g['Season'].tolist()))
        num_seasons    = g['Season'].nunique()
        player         = g['Player'].iloc[0]
        gy             = g['GradYr'].iloc[0]

        w   = int(g['W'].fillna(0).sum())
        l   = int(g['L'].fillna(0).sum())
        app = int(g['APP'].fillna(0).sum())
        gss = int(g['GS_P'].fillna(0).sum())
        cg  = int(g['CG'].fillna(0).sum())
        so  = int(g['SO'].fillna(0).sum())
        sv  = int(g['SV'].fillna(0).sum())
        h_p = int(g['H_P'].fillna(0).sum())
        r_p = int(g['R_P'].fillna(0).sum())
        er  = int(g['ER'].fillna(0).sum())
        bb_p= int(g['BB_P'].fillna(0).sum())
        k_p = int(g['K_P'].fillna(0).sum())
        pch = g['Pitches'].fillna(0).sum()

        # Sum IP in thirds
        t_thirds = sum(ip_thirds(v) for v in g['IP'])
        ip_display = thirds_str(t_thirds)
        ip_dec_val = t_thirds / 3.0

        era_calc = round(er * 27 / t_thirds, 2) if t_thirds > 0 else None
        wpct     = round(w/(w+l),3) if (w+l) > 0 else None
        k9       = round(k_p * 27 / t_thirds, 1) if t_thirds > 0 else None
        bb9      = round(bb_p * 27 / t_thirds, 1) if t_thirds > 0 else None
        whip     = round((h_p + bb_p) / ip_dec_val, 2) if ip_dec_val > 0 else None

        rows.append([player, gy, pk, num_seasons, seasons_played,
                     era_calc, w, l, wpct, app, gss, cg, sv,
                     ip_display, ip_dec_val,
                     h_p, r_p, er, bb_p, k_p,
                     k9, bb9, whip,
                     int(pch) if pch else None])

    cols = ['Player','GradYr','PlayerKey','Seasons','SeasonList',
            'ERA','W','L','W%','APP','GS','CG','SV',
            'IP','IP_Dec',
            'H','R','ER','BB','K',
            'K/9','BB/9','WHIP','Pitches']
    df_out = pd.DataFrame(rows, columns=cols)
    # Filter out pitchers with 0 IP and sort by K
    df_out = df_out[df_out['IP_Dec'] > 0].sort_values('K', ascending=False).reset_index(drop=True)
    return df_out

