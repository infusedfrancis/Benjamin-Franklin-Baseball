MIN_PA_FACTOR = 2.1   # PA per team game to qualify for batting rate records
MIN_IP_SS     = 13.0  # min IP to qualify for pitching rate records

def build_season_records(df_b, df_p, pa_factor=MIN_PA_FACTOR, min_ip=MIN_IP_SS):
    """Return a list of record-book dicts: best single-season for each category."""
    team_games = df_b.groupby('Season')['GP'].max()

    def bat_record(col, higher_is_better=True, qualified_only=False):
        if qualified_only:
            mask = df_b.apply(
                lambda r: n(r['PA']) >= math.ceil(team_games.get(r['Season'], 0) * pa_factor)
                          and n(r['AB']) > 0, axis=1)
            src = df_b[mask].copy()
        else:
            src = df_b.copy()
        src = src.dropna(subset=[col])
        if src.empty:
            return None, None, None, None
        idx = src[col].idxmax() if higher_is_better else src[col].idxmin()
        row = src.loc[idx]
        return row[col], row['Player'], row['Class'], row['Season']

    def pit_record(col, df_src, higher_is_better=True):
        df_src = df_src.dropna(subset=[col])
        if df_src.empty:
            return None, None, None, None
        idx = df_src[col].idxmax() if higher_is_better else df_src[col].idxmin()
        row = df_src.loc[idx]
        return row[col], row['Player'], row['Class'], row['Season']

    # Build IP-qualified pitching subset with pre-computed WHIP
    df_p_q = df_p.copy()
    df_p_q['_ip_dec'] = df_p_q['IP'].apply(ip_dec)
    df_p_q = df_p_q[df_p_q['_ip_dec'] >= min_ip].copy()
    df_p_q['WHIP_calc'] = (df_p_q['H_P'] + df_p_q['BB_P']) / df_p_q['_ip_dec']
    df_p_q['WHIP_calc'] = df_p_q['WHIP_calc'].round(3)

    pa_note = f'min {pa_factor} PA/game'
    ip_note = f'min {int(min_ip)} IP'
    records = []

    # ── Batting counting stats (no threshold) ────────────────────────────────
    for label, col in [
        ('Home Runs',    'HR'),
        ('Triples',      '3B'),
        ('Doubles',      '2B'),
        ('RBIs',         'RBI'),
        ('Runs Scored',  'R'),
        ('Hits',         'H'),
        ('Stolen Bases', 'SB'),  # SB is None for 2016-17/2017-18; excluded automatically
    ]:
        val, player, cls, season = bat_record(col)
        records.append({'Section': 'BATTING', 'Category': label,
                        'Record': int(val) if val is not None else None,
                        'Player': player, 'Class': cls, 'Season': season})

    # ── Batting rate stats (PA-qualified) ────────────────────────────────────
    for label, col in [('Batting Average', 'AVG'), ('OPS', 'OPS')]:
        val, player, cls, season = bat_record(col, qualified_only=True)
        records.append({'Section': 'BATTING', 'Category': f'{label}  ({pa_note})',
                        'Record': round(float(val), 3) if val is not None else None,
                        'Player': player, 'Class': cls, 'Season': season})

    # ── Pitching counting stats (no threshold) ───────────────────────────────
    for label, col in [('Strikeouts', 'K_P'), ('Wins', 'W')]:
        val, player, cls, season = pit_record(col, df_p.copy())
        records.append({'Section': 'PITCHING', 'Category': label,
                        'Record': int(val) if val is not None else None,
                        'Player': player, 'Class': cls, 'Season': season})

    # ── Pitching rate stats (IP-qualified) ───────────────────────────────────
    for label, col in [('ERA', 'ERA'), ('WHIP', 'WHIP_calc')]:
        val, player, cls, season = pit_record(col, df_p_q.copy(), higher_is_better=False)
        records.append({'Section': 'PITCHING', 'Category': f'{label}  ({ip_note})',
                        'Record': round(float(val), 3) if val is not None else None,
                        'Player': player, 'Class': cls, 'Season': season})

    return records


def write_season_records(ws, records, title, subtitle):
    """Write the record-book sheet with title, column headers, and section groups."""
    NUM_COLS = 5

    # ── Title rows ────────────────────────────────────────────────────────────
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=NUM_COLS)
    t = ws.cell(row=1, column=1, value=title)
    t.font = Font(bold=True, size=14, color=NAVY)
    t.alignment = Alignment(horizontal='center')
    ws.row_dimensions[1].height = 22

    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=NUM_COLS)
    s = ws.cell(row=2, column=1, value=subtitle)
    s.font = Font(italic=True, size=10, color='555555')
    s.alignment = Alignment(horizontal='center')
    ws.row_dimensions[2].height = 16

    # ── Column headers at row 3 ───────────────────────────────────────────────
    headers = ['Category', 'Record', 'Player', 'Class', 'Season']
    header_fill = PatternFill('solid', fgColor=NAVY)
    header_font = Font(bold=True, color=GOLD, size=11)
    for c, h in enumerate(headers, 1):
        cell = ws.cell(row=3, column=c, value=h)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal='center', vertical='center')
    ws.row_dimensions[3].height = 18

    # ── Data rows ─────────────────────────────────────────────────────────────
    section_fill = PatternFill('solid', fgColor='2A5298')
    section_font = Font(bold=True, color=WHITE, size=10)
    lgray  = PatternFill('solid', fgColor=LGRAY)
    white  = PatternFill('solid', fgColor=WHITE)
    thin   = Side(style='thin', color='CCCCCC')
    border = Border(bottom=thin)

    row_num = 4
    current_section = None
    section_row_count = 0
    rate_rows = []

    for rec in records:
        sec = rec['Section']
        if sec != current_section:
            ws.merge_cells(start_row=row_num, start_column=1,
                           end_row=row_num, end_column=NUM_COLS)
            cell = ws.cell(row=row_num, column=1, value=f'── {sec} ──')
            cell.fill = section_fill
            cell.font = section_font
            cell.alignment = Alignment(horizontal='center', vertical='center')
            ws.row_dimensions[row_num].height = 16
            row_num += 1
            current_section = sec
            section_row_count = 0

        fill = lgray if section_row_count % 2 == 0 else white
        section_row_count += 1

        is_rate = any(kw in str(rec['Category'])
                      for kw in ('Average', 'OPS', 'ERA', 'WHIP'))
        for c, val in enumerate([rec['Category'], rec['Record'],
                                  rec['Player'], rec['Class'], rec['Season']], 1):
            cell = ws.cell(row=row_num, column=c, value=val)
            cell.fill = fill
            cell.border = border
            cell.alignment = Alignment(
                horizontal='left' if c == 1 else 'center', vertical='center')
        if is_rate and rec['Record'] is not None:
            rate_rows.append(row_num)
        row_num += 1

    # ── Column widths ─────────────────────────────────────────────────────────
    ws.column_dimensions['A'].width = 36
    ws.column_dimensions['B'].width = 12
    ws.column_dimensions['C'].width = 20
    ws.column_dimensions['D'].width = 8
    ws.column_dimensions['E'].width = 12

    # ── Apply #.000 to rate-stat Record cells ────────────────────────────────
    for r in rate_rows:
        ws.cell(row=r, column=2).number_format = _RATE_FMT

    ws.freeze_panes = 'A4'


season_records = build_season_records(df_bat, df_pit)

ws11 = wb.create_sheet("Season Records")
write_season_records(
    ws11, season_records,
    title="Single-Season Records  –  Benjamin Franklin Chargers",
    subtitle=(
        f"Best single-season performances, 2016-17 through 2025-26  |  "
        f"Batting rate stats require {MIN_PA_FACTOR} PA/game  |  "
        f"Pitching rate stats require {int(MIN_IP_SS)} IP  |  "
        f"SB not recorded in 2016-17 or 2017-18"
    )
)

